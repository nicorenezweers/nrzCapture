//! Frontend der Bildschirmaufnahme: Aufnahme-Leiste, Steuerleiste, Warnhinweis, Countdown, Auswahl-/Aufnahmerahmen,
//! Klick-Hervorhebung und Tasten-Overlay. Port von Capso `RecordingToolbar`, `RecordingControlsWindow`,
//! `RecordingWarningPanel`, `CountdownView`, `SelectionBorderWindow`, `RecordingBorderWindow`,
//! `ClickHighlightWindow`, `KeyPressOverlayWindow`. Backend: `src-tauri/src/record.rs`.
mod controls;
mod overlays;
mod toolbar;

use leptos::prelude::*;

pub fn route(r: &str) -> Option<AnyView> {
    Some(match r {
        "rec-toolbar" => view! { <toolbar::Toolbar /> }.into_any(),
        "rec-controls" => view! { <controls::Controls /> }.into_any(),
        "rec-warning" => view! { <controls::Warning /> }.into_any(),
        "rec-countdown" => view! { <overlays::Countdown /> }.into_any(),
        "rec-frame" => view! { <overlays::Frame /> }.into_any(),
        "rec-clicks" => view! { <overlays::Clicks /> }.into_any(),
        "rec-keys" => view! { <overlays::Keys /> }.into_any(),
        _ => return None,
    })
}

/// Zeit als mm:ss (Capso `formatTime`).
pub fn format_time(secs: f64) -> String {
    let s = secs.max(0.0) as u64;
    format!("{:02}:{:02}", s / 60, s % 60)
}

